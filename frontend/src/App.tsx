const time = (s: string) => {
  const m = Math.max(0, Math.floor((Date.now() - Date.parse(s)) / 60000));
  return m < 1
    ? "just now"
    : m < 60
      ? m + "m ago"
      : m < 1440
        ? Math.floor(m / 60) + "h ago"
        : Math.floor(m / 1440) + "d ago";
};
const linked = (body: string) =>
  body.split(/(https?:\/\/[^\s]+)/g).map((part, i) =>
    /^https?:\/\//.test(part) ? (
      <a
        className="post-link"
        key={i}
        href={part}
        target="_blank"
        rel="noreferrer"
      >
        {part.includes("bscscan.com/tx/")
          ? "view receipt ↗"
          : part.replace("https://", "")}{" "}
      </a>
    ) : (
      part
    ),
  );
